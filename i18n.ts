const TRANSLATIONS: Record<Locale, Record<TranslationKey, string>> = {
  en: EN_TRANSLATIONS,
  ko: KO_TRANSLATIONS,
};

export function normalizeLocale(value: unknown): Locale {
  if (typeof value !== "string") {
    return "en";
  }
  const normalized = value.trim().toLowerCase().replace(/_/g, "-");
  return normalized === "ko" || normalized.startsWith("ko-") ? "ko" : "en";
}

export function translate(locale: Locale, key: TranslationKey, vars: TranslationVars = {}): string {
  const template = TRANSLATIONS[normalizeLocale(locale)][key] ?? EN_TRANSLATIONS[key] ?? key;
  return template.replace(/\{\{\s*([a-zA-Z0-9_-]+)\s*\}\}/g, (match, name: string) => {
    const value = vars[name];
    return value === undefined || value === null ? match : String(value);
  });
}

export function normalizeLocalePreference(value: unknown): LocalePreference {
  return value === "en" || value === "ko" ? value : "auto";
}

export function resolveLocale(preference: LocalePreference, obsidianLocale: unknown): Locale {
  if (preference === "en" || preference === "ko") return preference;
  return normalizeLocale(obsidianLocale);
}